import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {assertSafePath,isPreviewable,tokenMatches,scrubOutput} from '../server/core.mjs';
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'kael-core-'));
fs.writeFileSync(path.join(tmp,'hello.txt'),'safe');
fs.mkdirSync(path.join(tmp,'nested'));
fs.symlinkSync('/etc/passwd',path.join(tmp,'shortcut'));
test.after(()=>fs.rmSync(tmp,{recursive:true,force:true}));
test('workspace root resolves correctly',()=>assert.equal(assertSafePath(tmp,''),fs.realpathSync(tmp)));
test('nested path resolves in workspace',()=>assert.equal(assertSafePath(tmp,'nested'),path.join(tmp,'nested')));
test('rejects parent traversal',()=>assert.throws(()=>assertSafePath(tmp,'../../etc/passwd')));
test('rejects absolute paths',()=>assert.throws(()=>assertSafePath(tmp,'/etc/passwd')));
test('rejects hidden directories',()=>assert.throws(()=>assertSafePath(tmp,'.ssh/id_rsa')));
test('rejects symlink files',()=>assert.throws(()=>assertSafePath(tmp,'shortcut')));
test('rejects null bytes',()=>assert.throws(()=>assertSafePath(tmp,'bad\0path')));
test('rejects too-long paths',()=>assert.throws(()=>assertSafePath(tmp,'a'.repeat(2049))));
test('rejects Windows-style traversal',()=>assert.throws(()=>assertSafePath(tmp,'..\\etc\\passwd')));
test('previewable small markdown',()=>assert.equal(isPreviewable('README.md',200),true));
test('large files cannot be previewed',()=>assert.equal(isPreviewable('test.md',200001),false));
test('binary preview disabled',()=>assert.equal(isPreviewable('credentials.bin',10),false));
test('access key comparison',()=>{assert.equal(tokenMatches('abcd','abcd'),true);assert.equal(tokenMatches('abcd','abc0'),false);assert.equal(tokenMatches('abcd','abc'),false);});
test('scrubs known credential formats',()=>assert.ok(!scrubOutput('token sk-testabcdefghijklmnopqrstuvwx').includes('abcdefghijklmnopqrstuvwx')));